/**
 * 抹掉注释 —— 判据扫源码时的**唯一**一份实现。
 *
 * ## 为什么需要它
 *
 * 「注释冒充正文」是本仓反复栽的那条坑（`docs/审计规范.md` 第三节）:
 * 判据写「源码里不许出现 X」，而注释里正好**举例**说明了旧的 X，
 * 于是判据在正确实现上红。解法是先抹掉注释再判。
 *
 * ## 为什么收成一份
 *
 * 这个工具曾经被复制到**八份**用例里，而它们**已经分叉了**:
 *
 * ```text
 * rulesetEra / softCapVisibility / veinVisibility   三种注释都抹
 * deadFallback / assertionLiveness / testDeterminism 只抹块注释与整行 //
 * breakthroughCost / weatherUnitConsistency          三种都抹，且避开 ://
 * ```
 *
 * 两种漏法都真实存在:
 *
 * 1. **漏 HTML 注释** —— `.vue` 里的注释就是 `<!-- … -->`。只抹块注释与行注释的
 *    版本对模板注释完全无效，而那正是 Vue 项目里最常见的一种；
 * 2. **漏行尾 `//`** —— 只认整行注释的实现，对 `const a = 1; // 旧写法` 无效，
 *    判据照样举报正确实现。
 *
 * 分叉方向不对称:**宽的那份**能挡住误报，**窄的那份**挡不住 —— 而它们是同一个
 * 判据工具的副本，谁也不会去核对另一份。
 *
 * ## 三条口径
 *
 * - 三种注释都抹:HTML / 块 / 行；
 * - **行尾 `//` 也剥**，但要避开 `://`（那会把 URL 后半截吃掉，连带抹掉真代码）；
 * - 只抹注释，**不动任何真代码** —— 判据 `stripCommentsParity.spec` 用一份
 *   「每行注释后都跟着真代码」的样本双向核过。
 */
export function stripComments(src: string): string {
  return (
    src
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/\/\*[\s\S]*?\*\//g, "")
      // `(^|[^:])` 保住 `http://` 这类；`$1` 把那个前缀字符放回去
      .replace(/(^|[^:])\/\/[^\n]*/g, "$1")
  );
}
