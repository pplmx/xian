/**
 * 品评 —— 九档品质各一句,说清「这一档凭什么」。
 *
 * ## 为什么单独成表,而不是往 QualityDef 里再加一个字段
 *
 * `data/qualities` 管的是**规则**:倍率、词条条数区间、掉落窗口与权重。
 * 一张规则表每年被数值调整翻几遍,而「凡品」那句评语不该跟着一起改。
 * 与 `data/beastFamilies`(形归族类表)、`data/petVows`(话归契语表)同一条分工:
 * 内容与规则分处两个文件,改一边不必碰另一边。
 *
 * ## 品评与品阶名各管一件事
 *
 *   品阶名 —— 分类:凡 / 良 / 精 / 灵 / 玄 / 地 / 天 / 仙 / 神。两三个字,进得去格子与徽章。
 *   品评  —— 分量:这一档在**这一套体系里**站在哪儿。一句半,进得去器评帖的眉题行。
 *
 * 所以品评不重复品阶名(不写「凡品之物」),也不写数值(数字归 mult / affixes 管)。
 * 它回答的是玩家看完九档之后仍在心里问的那一句:「天品和仙品到底差在哪?」——
 * 差在**话的分量**,与差在词条条数与倍率,两件事各有出处。
 *
 * ## 为什么不叫「品质描述」
 *
 * 「描述」会被读成 flavor(「玄铁铸就,大巧不工」那种讲物件的句子)。品评讲的是
 * **档**,不是物:同一句话适用于这一档里的每一件,从青竹剑到神魔镜都得成立。
 */
import type { QualityId } from "@/types";

/**
 * 九档品评。
 *
 * 逐档往上抬一层:凡品只说「堪用」,神品说到「见之当拜」。抬的是**评价的口气**,
 * 不是字数 —— 九句都压在一行以内(见 qualityVerdicts.spec 的排版上界),读起来才不像广告。
 * 刻意没有「后一档必须更长」这类阶梯判据:那会逼人把短句拉长去够字数,而短正是它的好处。
 */
export const QUALITY_VERDICTS: Record<QualityId, string> = {
  mortal: "山野之物,堪用而已",
  fine: "炼得成形,已有章法",
  excellent: "灵机内蕴,非俗手可成",
  spirit: "玄机暗合,器中有道",
  profound: "地气所钟,可镇一方",
  earth: "承得住山河,也承得住人",
  heaven: "天成其纹,非人力可摹",
  immortal: "仙风入器,自有一段清旷",
  divine: "开天之属,见之当拜",
};

/**
 * 某一档的品评。
 *
 * 表是 `Record<QualityId, string>`,类型上已经是完备的;这里再兜一层空串,
 * 是为了「将来有人加一档品质、忘了加品评」时界面不会印出 `undefined` ——
 * 那种句子在器评帖的眉题行里格外刺眼。空串由调用方判空整句不出。
 */
export function qualityVerdict(quality: QualityId): string {
  return QUALITY_VERDICTS[quality] ?? "";
}
