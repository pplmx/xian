/** 随机道号生成 */
import { RandomService } from "@/utils/random";

const SURNAMES = [
  "云",
  "风",
  "叶",
  "苏",
  "洛",
  "沈",
  "顾",
  "陆",
  "秦",
  "楚",
  "萧",
  "陵",
  "白",
  "墨",
  "凌",
  "江",
];
/**
 * 名。**单字与双字分开计数**:单字名配单姓是两字(「云尘」),
 * 双字名配单姓是三字(「云临渊」)—— 玩家掷出来的道号长短会不同,这是有意的
 * (中文人名本就两字三字并存),但**比例要大致相当**。
 *
 * 从前是 4 单 : 12 双(25% : 75%),玩家七成半掷到三字名。补 4 个单字后是 8 : 12。
 */
const GIVEN = [
  "尘",
  "青",
  "霜",
  "砚",
  "川",
  "澈",
  "岑",
  "枢",
  "临渊",
  "疏影",
  "照夜",
  "归鸿",
  "扶摇",
  "听雪",
  "孤鹤",
  "无咎",
  "知非",
  "守拙",
  "望舒",
  "惊鸿",
];

export function randomDaoName(rng: RandomService): string {
  return rng.pick(SURNAMES) + rng.pick(GIVEN);
}
