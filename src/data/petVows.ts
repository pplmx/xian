/**
 * 灵兽契语 —— 每只灵兽对你说的那一句。
 *
 * ## 为什么单独成表,而不是再加一个 PetDef 字段
 *
 * 与 `data/beastFamilies` 同一条分工:形态归族类表、叙事归这张表,`PetDef` 只留
 * 「它是什么、给我什么」。于是加一句契语不必动类型、不必迁移存档,也不会让
 * 灵兽表那一行变得难读。
 *
 * ## 契语与 desc 的区别(同一屏同时出现,两句不许说同一件事)
 *
 *   `desc` —— **它是什么**:尾生青羽、背驮山岳、鳞下流火。写给旁观者。
 *   `vow`  —— **它对你是什么样**:见到亮的东西先往你这边看一眼。写给同行的人。
 *
 * 所以契语只在你**真唤它相伴**时露面(名号页的「此刻相伴」与图鉴条目),
 * 灵兽谱的长列表不铺这一句 —— 四十句并排就不再是契语,是一张文案表。
 *
 * ## 语气随品阶加深,但素朴的那几只也是一句话
 *
 * 精品写日常的相处,地品起写来历,仙品以上写天地与道的尺度。**不与数值挂钩**:
 * 契语不给任何加成,也不参与选哪一只 —— 它和器铭同一条纪律(见 core/inscription):
 * 描述「它是谁」,不替玩家做决定。
 *
 * 每句都不带数字:数字该来自 `mods` 与 `petTraitText`,两样混在一起,改常数那天
 * 契语就开始撒谎。
 */
