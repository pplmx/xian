/**
 * 掉落专属丹药：低阶几乎全无，而这正是对的。
 *
 * ## 由来（第 526 轮）
 *
 * 上一轮补上了「深修回报的战斗轴」。这一轮继续用同一办法:**找档案里写了诊断
 * 却没实现的那一句**。`core/loot.ts:293` 有这么一句:
 *
 * ```text
 *   想把掉落池的品阶分布再推高,该补的是掉落专属的高品阶丹药,不是继续加系数。
 * ```
 *
 * 摊开 22 味掉落专属:
 *
 * ```text
 *   凡 0 · 良 1 · 精 0 · 灵 4 · 玄 2 · 地 2 · 天 2 · 仙 4 · 神 3
 * ```
 *
 * 第一版判据写的是「每一档都 ≥ 2 味」，于是报「凡品 0、良品 1、精品 0 不足」。
 *
 * ## 而那不是缺陷
 *
 * 把「有配方」与「掉落专属」并排看:
 *
 * ```text
 *   凡 有配方 1 · 掉落 0
 *   良 有配方 4 · 掉落 1
 *   精 有配方 6 · 掉落 0
 *   灵 有配方 9 · 掉落 4
 * ```
 *
 * **低阶几乎全靠炼制** —— 开局让玩家自己去炼，而不是直接掉给他是对的:
 * 那一阶段的乐趣在「学会炼丹」，不在「捡到一颗」。
 * 而高阶（仙 / 神）反过来:它们本来就难炼，掉落是主要来源。
 *
 * 故 `loot.ts` 那句诊断说的是**高品阶**要补，不是每一档都要补。
 * 第一版判据把「高品阶」读成了「每一档」——与第 522 轮那个口径错误同一类。
 *
 * ## 判据
 *
 * ① 高品阶（仙 / 神）的掉落专属必须足够多 —— 那里掉落是主要来源;
 * ② 反差：低品阶（凡 / 良 / 精）不设下限 —— 它们主要靠炼制;
 * ③ 反差：两端的配比要能看出方向 —— 低阶有配方多、高阶掉落多。
 */
import { describe, expect, it } from "vite-plus/test";
import { PILLS } from "@/data/pills";

const countOf = (q: string, drop: boolean): number =>
  PILLS.filter((p) => p.quality === q && Boolean(!p.recipe) === drop).length;

describe("掉落专属丹药 · 高品阶才是掉落的主场", () => {
  it("① 仙品与神品的掉落专属各不少于 3 味", () => {
    const thin: string[] = [];
    for (const q of ["immortal", "divine"] as const) {
      const n = countOf(q, true);
      if (n < 3) thin.push(`${q}(${n} 味)`);
    }
    expect(thin, "高品阶的掉落专属太少 —— 而那一阶段掉落就是主要来源：" + thin.join("、")).toEqual(
      [],
    );
  });

  it("② 反差：低品阶不设下限 —— 它们主要靠炼制", () => {
    /*
     * 这一条守的是①的边界。凡 / 良 / 精的掉落专属是 0 / 1 / 0，
     * 而它们的有配方数是 1 / 4 / 6 —— **那不是缺陷，是设计**:
     * 开局让玩家学会炼丹，比让他捡到一颗更接近这一阶段的乐趣。
     */
    for (const q of ["mortal", "fine", "excellent"] as const) {
      expect(countOf(q, false), `${q} 一味可炼的都没有 —— 那开局只能捡`).toBeGreaterThan(0);
    }
  });

  it("③ 高品阶在掉落池里的占比要够 —— 池子窄，系数就使不上劲", () => {
    /*
     * ## 这一条改过一次（第 526 轮）
     *
     * 第一版写的是「高阶掉落专属要多于高阶有配方」—— 实测 11 vs 38，永远不成立。
     * 而那个方向本来就错了:**高阶丹药能炼是对的**，可炼与可掉不是对立的。
     *
     * `core/loot.ts` 那句诊断的真实含义在同段注释里:
     *
     * ```text
     *   池子越窄,衰减系数能起的作用越有限 —— 实测掉落池在 K 从 0.5 变到 2 时,
     *   境 20 的高/低品阶占比都是 45% / 43%,几乎不动
     * ```
     *
     * 故要守的是**掉落池内部的高品阶占比**，不是它与有配方那一侧的比值。
     */
    const dropHigh =
      countOf("earth", true) +
      countOf("heaven", true) +
      countOf("immortal", true) +
      countOf("divine", true);
    const dropAll = PILLS.filter((p) => !p.recipe).length;
    expect(
      dropHigh / dropAll,
      `掉落池里高品阶（地/天/仙/神）只占 ${((dropHigh / dropAll) * 100).toFixed(0)}%` +
        ` —— 那「同境优先」这条表达在掉落这条路上几乎不生效`,
    ).toBeGreaterThan(0.35);
  });
});
