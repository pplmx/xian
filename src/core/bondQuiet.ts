/**
 * 同行帖的「此刻没有未了之言」—— 那一片空白其实是四种不同的处境。
 *
 * ## 缺口（本轮实测确认）
 *
 * `BondDialog` 的 `bond-quiet` 在「没有待答的事」时一句说尽:
 *
 * ```text
 * 此刻没有未了之言
 * 多走几处地界，新的相遇会自己找上来。     ← 这一句
 * ```
 *
 * 而它所在的 `v-else` 是**至少四件事共用**的一个出口:
 *
 * ```text
 * ① 她还在，只是这一会儿没事说     → 「多走走」成立
 * ② 七件事全历尽了                 → 走多少地界都不会再有
 * ③ 她已经陨落                     → 已有专门那句
 * ④ 她已经离去                     → 已有专门那句
 * ```
 *
 * ②是本轮量出来的:七件事全历之后,「这一世还开着几件」那个读数回 0,
 * 四次情境位 (`bossDefeated` / `nearDeath` / `enterPlace` / `firstVictory`)
 * **全部回 null**。而这时界面还在说「多走几处地界，新的相遇会自己找上来」。
 *
 * 更糟的是这句话在这一档上有双重的错:
 *
 * ```text
 * 七件事走完 → 不会再有新的共同事件（这是内容用完了，不是"你走得不够"）
 * 而且已经有同行者 → meet() 直接 false，新的人根本进不来
 * ```
 *
 * 也就是说：玩家读到的建议是一条**永远做不到**的建议。这正是本仓
 * `docs/usage.md` 那句「终点不该被写成中转站」的同一个形状 ——
 * 世界到顶之后，指引还在说「再往前走」。
 *
 * ## 判据口径
 *
 * 这一层只回答「此刻该说哪一句」，不判措辞美感。四种处境各有一句话，
 * 而「全历尽」那一档必须**说出已经没有往下的事了**，不能说「多走走」。
 */

/** 此刻为什么没有未了之言 */
export type BondQuietKind =
  /** 她还在，只是这一会儿没事说 */
  | "idle"
  /** 这一世的共同事件全历尽了 —— 走多少路都不会再有新的 */
  | "exhausted"
  /** 她死在了这一世 */
  | "fallen"
  /** 她半途离去 */
  | "departed";

export interface BondQuietLine {
  kind: BondQuietKind;
  /** 那一行短标题 */
  title: string;
  /** 底下那句解释 */
  copy: string;
}

/**
 * 这本书还剩几页没翻。
 *
 * 只数**这一世还开着**的那些(未历 + 门槛已到)——与 `daoluService` 里那个
 * 同名读数同一套条件,但**不读 store**:调用方把两个数传进来,故这一层可测。
 *
 * 两种「零」要分开:
 *
 * ```text
 *   done >= total              这一世真的走完了   → 再走也没用（文案要说穿）
 *   done < total 而盒子暂时空   境界不够，还没解锁 → 「多走走」仍是对的
 * ```
 *
 * 故这里判的是前者,不是「盒子此刻空不空」——后者会把「还差一境」说成「已经到头」。
 */
export interface BondQuietFacts {
  fallen: boolean;
  departed: boolean;
  /** 已历的共同事件数 */
  done: number;
  /** 这一世总共几件（`BOND_EVENTS.length`） */
  total: number;
}

/**
 * 这一刻该说哪一句。
 *
 * 顺序有讲究:**死与散优先于「没事说」** —— 人不在了，「多走走」自然也不成立；
 * 而「历尽」排在最后，它只在人还在的时候才有意义。
 */
export function bondQuietLine(facts: BondQuietFacts): BondQuietLine {
  if (facts.fallen) {
    return {
      kind: "fallen",
      title: "此世同行已止",
      copy: "人不随转世回来，历世同行仍留在卷末。",
    };
  }
  if (facts.departed) {
    return {
      kind: "departed",
      title: "此世已分道",
      copy: "关系停在此处，走远的人不会再追问。",
    };
  }
  /*
   * 「历尽」的判据是 done >= total 且 total > 0。
   *
   * total 为 0 时不能判历尽 —— 那是内容表为空（配置坏了），
   * 说「此书已尽」会把一个配置问题说成设计。那时退回「没事说」。
   */
  if (facts.total > 0 && facts.done >= facts.total) {
    return {
      kind: "exhausted",
      title: "此世的缘分已尽数走过",
      /*
       * 不说「再无新的」而说「这一世的」:下一世还有别人、还有别的缘 ——
       * 这是「此世」的内容用完了,不是这个系统到顶了。两者的区别，
       * 正是本仓在「渡劫飞升」与「混沌道祖」之间分过的那一次。
       */
      copy: "这一世的共同经历已经全部走过；往后的路，你们只并肩，不再有新的事。",
    };
  }
  return {
    kind: "idle",
    title: "此刻没有未了之言",
    copy: "多走几处地界，新的相遇会自己找上来。",
  };
}
