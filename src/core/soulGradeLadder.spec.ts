/**
 * 器魂六阶的倍率阶梯 —— 这一条此前没有任何判据在管。
 *
 * ## 缺口（第 395 轮实测）
 *
 * 法宝有一整族横向审计（`artifactLadder.spec` 的五条:族内相邻档增长率、不许倒退、
 * 九档分布不空……），而**器魂六阶一条都没有**。`souls.spec` 那 12 条管的是
 * 「六类器魂的名实相符」「品质映射单调」「高阶强于低阶」—— 都是**两端**与**类型**，
 * 中间那五格怎么走，没人问过。
 *
 * `balanceCoverage.spec` 的 `WANTED` 清单里也没有「器魂」这一行。
 *
 * ## 实测到的两个事实
 *
 * 一、倍率是 `1.0 / 1.25 / 1.5 / 1.75 / 2.0 / **2.3**`。前五档是精确的
 *    `1 + 0.25×rank`，**只有末档 `化真` 差 0.05**（应为 2.25）。
 *
 * 二、若按等差 2.25，相邻档的**相对**涨幅是单调递减的：
 *
 * ```text
 *   阶0→1 +25.0%   1→2 +20.0%   2→3 +16.7%   3→4 +14.3%   4→5 +12.5%
 * ```
 *
 *    而用 2.3，末档回升到 **+15.0%** —— 阶梯在最后一格鼓了一下。
 *
 * ## 这一条为什么不断言「2.3 是笔误」
 *
 * 两种读法都成立：
 *
 * ```text
 *   2.25 读法   前五档都是 1 + 0.25×rank，末档照写 —— 2.3 是手误
 *   2.3  读法   末阶是「化真」，刻意让最后一步不那么小气 —— 是设计
 * ```
 *
 * 源码注释只说了「阶差刻意压得比装备品质差距小得多」，没有说末档该不该鼓。
 * **故这条判据不替作者选**，它钉的是三件两种读法都要成立的事：
 *
 * ① 六档**严格递增**（不是「不倒退」—— 器魂没有「白凝一档」这种东西）；
 * ② 相邻档的倍率增量落在同一个量级（不许出现某一档暴涨或几乎不涨）；
 * ③ 品质 rank 0~8 → 六阶的映射单调不减，且八档品质全被用上。
 *
 * ②这条是真正缺的那一条:它挡的是「有人手改某一档的 mult」这类静默事故 ——
 * 而现在没有任何东西会因此变红。
 *
 * ## 末档那个 0.05 记在这里，不在文档里单独开一节
 *
 * 它太小(相对 2.25 约 2.2%),不值得为它改数或改文档;
 * 但它是**当前口径的一部分**,故钉在判据里:哪天有人把它改成 2.25,
 * ②仍然绿(2.25 也在同一量级),而下面那条「现值快照」会红,
 * 逼那个人来读这段注释、自己决定。
 */
import { describe, expect, it } from "vite-plus/test";
import { SOUL_GRADES, soulGradeOfQuality } from "@/data/souls";
import { QUALITIES } from "@/data/qualities";

describe("器魂六阶 · 倍率阶梯", () => {
  it("六档严格递增 —— 不是「不倒退」，是每一档都真的更强", () => {
    /*
     * 用 `>` 而不是 `>=`:器魂是「从器物上剥下来」的一层,
     * 没有「凝出来了但和上一阶一样」这种处境。相等就意味着有一档白凝。
     */
    for (let i = 1; i < SOUL_GRADES.length; i += 1) {
      expect(
        SOUL_GRADES[i]!.mult,
        `${SOUL_GRADES[i]!.name}(×${SOUL_GRADES[i]!.mult})没有比 ${SOUL_GRADES[i - 1]!.name}(×${SOUL_GRADES[i - 1]!.mult})更强 —— 那一档等于白凝`,
      ).toBeGreaterThan(SOUL_GRADES[i - 1]!.mult);
    }
  });

  it("相邻档的增量同量级 —— 不许某一档暴涨或几乎不涨", () => {
    /*
     * 这是真正缺的那一条。`souls.spec` 只比了阶 0 与阶 5 的两端,
     * 中间那一格若被手改成 3.5 或 1.01,它照样绿。
     *
     * 判据按**增量**取上下界,而不按「涨幅百分比」:
     * 倍数本身是等差的,故增量是同一个量级;而相对涨幅天然递减
     * (见文件头那张表),用百分比断反而会误伤。
     */
    const steps = SOUL_GRADES.slice(1).map((g, i) => g.mult - SOUL_GRADES[i]!.mult);
    const lo = Math.min(...steps);
    const hi = Math.max(...steps);
    /*
     * 上界 1.5 倍、下界 1/1.5 —— 只挡量级错误(把 0.25 写成 0.03 或 2.5),
     * 不挡「末档稍鼓一点」这种刻意的口味差别。
     */
    expect(
      hi / lo,
      `相邻档增量的最大与最小差 ${(hi / lo).toFixed(2)} 倍(${lo.toFixed(3)} ~ ${hi.toFixed(3)})—— ` +
        "某一档暴涨或几乎不涨，阶梯不再是阶梯",
    ).toBeLessThanOrEqual(1.5);
    expect(lo, "最小的那一档增量几乎为零 —— 有一阶白凝了").toBeGreaterThan(0.01);
  });

  it("品质 rank 0~8 全部映射到六阶，且单调不减", () => {
    /*
     * `souls.spec` 有一条「品质映射到六阶,且单调不减」。这一条**不重复它**,
     * 补的是另一半:九档品质要**全部落在**六阶里,不许有一档映射失败(返回 undefined)。
     */
    let prev = -1;
    for (const q of QUALITIES) {
      const g = soulGradeOfQuality(q.rank);
      expect(g, `品质 ${q.name}(rank ${q.rank})没映射到任何器魂阶`).toBeDefined();
      expect(
        g.rank,
        `品质 ${q.name}(rank ${q.rank})映射到的阶(${g.rank})比上一档(${prev})更低`,
      ).toBeGreaterThanOrEqual(prev);
      prev = g.rank;
    }
    // 顶端必须真的到得了最高阶,否则「化真」是不可得的
    expect(
      soulGradeOfQuality(QUALITIES.length - 1).rank,
      "最高品质映射不到化真 —— 那它不可得",
    ).toBe(SOUL_GRADES.length - 1);
  });

  it("倍率现值快照 —— 改它的人先来读文件头那段「两种读法」", () => {
    /*
     * 与 `engineParity` 的「迁移前冻结旧口径」同一条纪律:
     * 把当前的数按位钉住,让**改动变成一次有意识的动作**。
     *
     * 特别注意末档:`2.3` 与等差应有的 `2.25` 差 0.05。文件头写了两种读法,
     * 若有人改成 2.25,这条会红 —— 那是**提醒**,不是禁止:读过之后把这里一起改掉即可。
     */
    expect(
      SOUL_GRADES.map((g) => g.mult),
      "器魂六阶的倍率被改了 —— 文件头记着末档 2.3 与等差的 2.25 这两种读法，先读一遍再决定",
    ).toEqual([1.0, 1.25, 1.5, 1.75, 2.0, 2.3]);
  });
});
