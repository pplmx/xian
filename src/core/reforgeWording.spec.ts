/**
 * 自动重铸那一行必须是「至多」，不是「预计」。
 *
 * ## 由来（第 330 轮）
 *
 * `docs/usage.md` 的「重铸预算」那一节:
 *
 * > - **是「至多」不是「预计」**—— 自动重铸会提前收手（命中即停、付不起即停），
 * >   所以预算次数对应的是上界，那是能算准的；「预计」要按命中概率加权，
 * >   那另一个数已经由逐条的「约 N 次」给出。**两个数混成一句会自相矛盾。**
 *
 * 而 `ui/reforgeBudget.ts` 的文件头也写着同一段论证（「为什么是『至多』而不是『预计』」）。
 *
 * ## 为什么需要判据
 *
 * 两个词在玩家那边是两件事:
 *
 * ```text
 * 至多洗 50 次    上界。玩家据此判断「最坏情况我付得起吗」
 * 预计洗 50 次    期望。玩家据此判断「我大概会花这么多」—— 而那要按命中概率加权
 * ```
 *
 * 改成后者，玩家会把上界当期望:高估花费（不敢按），或按错预算（按完发现付不起）。
 *
 * 而三项检查都不管:
 *
 * ```text
 * 类型系统      文案里的两个字，管不到
 * 浏览器巡游    看得到「至多洗」这四个字，但看不出它该不该是「预计」
 * 既有判据      reforgeBudget.spec 八条全在测数值（总价 = 单价 × 次数、夹取、缺口），
 *               一条都没测这句话怎么说的
 * ```
 *
 * ## 判据
 *
 * ① 面板上确实有那句预算文案（防空转）;
 * ② 它写的是「至多」;
 * ③ 它**不写**「预计」—— 那个词在同一块里出现过就红。
 */
import { describe, expect, it } from "vite-plus/test";
import { readSource } from "@/test/readSource";

const PANEL = readSource("src/components/equipment/EquipReforgePanel.vue");

describe("自动重铸 · 预算那句是「至多」不是「预计」", () => {
  it("预算文案还在（防空转）", () => {
    expect(PANEL.length, "EquipReforgePanel 读出来是空的 —— 路径变了").toBeGreaterThan(1000);
    expect(PANEL, "找不到「洗」字 —— 这块大概被删了或改名了").toContain("洗");
  });

  it("写的是「至多」—— 那是能算准的上界", () => {
    expect(PANEL, "「至多洗」不见了 —— 若改成「预计」，玩家会把上界当成期望花费").toContain(
      "至多洗",
    );
  });

  it("这块里不写「预计」—— 那是另一个量，由逐条的「约 N 次」给出", () => {
    // 只看模板与代码，注释里解释「为什么不是预计」是正当的
    const withoutComments = PANEL.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    expect(
      withoutComments,
      "自动重铸这块出现了「预计」—— 上界与期望两个量混进同一块，玩家会算错账",
    ).not.toContain("预计");
  });
});
