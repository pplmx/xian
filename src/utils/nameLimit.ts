/**
 * 名字的上限 —— 本作所有「玩家自己起的名字」共用同一道尺。
 *
 * ## 为什么单独一个文件
 *
 * 这个 8 不属于任何一个模块:道号、构筑名、挑战书名、转世名号草稿都用它。
 * 放在 `stores/player` 里会让另外三处 import 一个 player store 才拿到常数 ——
 * 那是借来的依赖,读者会以为它们与角色有关。放在这里,它只是本作的输入约定。
 *
 * ## 为什么是 8
 *
 * 顶栏那行名字(`folio-head__name`)在 390 宽下大约放得下八个汉字,再多就靠
 * `truncate` 截了。截断是必要的兜底(旧档里可能有更长的名字),但**新输入**
 * 不该依赖它:玩家敲进去的字被悄悄削掉,不会报错也不会提示。
 *
 * ## 2026 年为此吃过两次
 *
 *   第一次:创建页有 `maxlength` 与 `slice` 两道,store 的 `setName` 一道都没有 ——
 *          契约活在错误的地方。修法是把常数收进 store(第 37 轮)。
 *   第二次:收完之后,另外三处**仍然各写一个 8**。它们是同一件事的不同场合,
 *          改一处不会带动其余 —— 而改的人不会想到要去搜四个文件(第 38 轮)。
 *
 * 故现在:定义一处,六处调用。
 */
