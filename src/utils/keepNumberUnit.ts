/**
 * 锁住「数字 + 量词」之间的空格,不让它在窄屏折成两行。
 *
 * 「灵石 998 万」在 390 宽下会被折成「998」/「万」两行 —— 数字与它的量词
 * 分开是最难读的折法,而 CSS 里对每个 span 加 `whitespace-nowrap` 既不现实
 * (文本是整句拼出来的),也会连带锁死整句。这里只把那一处普通空格换成
 * 不换行空格(U+00A0),折行照常,但数字不再与量词分手。
 *
 * 两个调用点(洞府建筑账、首页日课)此前各写一份,正则还不一样:
 * 洞府那份把 `万|亿|兆` 挂在**数字之后**(`[\d,.]+(?:万|亿|兆)?`),
 * 于是只锁住了「998万 灵石」这种无空格写法,「998 万 石」仍会拆;
 * 首页那份干脆不带换算单位。两处都漏了同一件事 —— 换算单位本身也是量词。
 * 现在它与石/铁/尘同列在断言里。
 */
const NUMBER_UNIT_GAP = /(\d[\d,.]*)\s+(?=[石铁尘株张载年次件层场阶枚缕时日]|万|亿|兆)/g;

export function keepNumberUnit(text: string): string {
  return text.replace(NUMBER_UNIT_GAP, "$1\u00a0");
}
