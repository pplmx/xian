/**
 * 宿慧折算那一句 —— 「读到几分」与「折多少宿慧」是两件事
 *
 * ## 缺口（上一轮自己造成的）
 *
 * 修仙录「随身所知」里三块读数挨着摆:
 *
 * ```text
 *   宿慧阶梯   1 / 340
 *   读通器谱   0 / 288 张
 *   器谱进度   雾隐长枪 90% 再 5 次 / 迷雾纱 50% 再 25 次
 * ```
 *
 * 而 `samsaraService.loreInsight` 折算宿慧时,器谱那一项用的是
 * **`isBlueprintMastered(v)` —— 满掌握(100%)才计一分,90% 是零分**。
 * 敌人认知同理(`>= ENEMY_LORE_MAX`)、丹方同理(`>= 1`)。
 *
 * 于是玩家读到「雾隐长枪 90%」时最自然的推断是「攒了不少宿慧」,
 * 实际一分没有。那一块是「器谱进度」那轮加的,当时只想着让玩家看见连续值,
 * 没接上它和宿慧之间的关系。
 *
 * ## 措辞:指向行动,不只陈述规则
 *
 * 玩家真正想知道的是「那我该砸哪张」,而答案正是进度块本身已经按「差几次」
 * 排好序的首行。故这一句把规则与行动连起来说,而不是只讲一条干巴巴的口径。
 *
 * 「详见说明」这类话不写 —— 那是把人从当前屏推走。
 */

/**
 * 一句宿慧折算口径,接在器谱进度下面。
 *
 * 与 `ui/offlineChainNote` 同一层:只算,不读 store。
 */
export function insightRulesNote(): string {
  return "宿慧只算「读通」那一档——读到九成仍计零分，下一锤先砸离读通最近的那张。";
}
