/**
 * 奇缘只能在线推进 —— 挂机等不到它,这件事得说出来
 *
 * ## 缺口:「离线不做替选」是有意设计,但没有玩家侧的解释
 *
 * `core/offline.ts` 的注释写得很清楚:
 *
 * ```text
 *   机缘/奇缘那类带代价选择的不做离线替选(在线可拒,离线不能替玩家拍板)
 * ```
 *
 * 理由充分 —— 奇缘的选择常常不可逆(救人 / 不救、履约 / 不履约),替玩家拍板
 * 等于替他做一个不能反悔的决定。**但玩家侧一个字都没有。**
 *
 * 而奇缘榜会写「待续第 2 段」,玩家挂机一天回来看到进度没动,最自然的解读
 * 是「坏了」或「被克扣了」。这条说明必须贴着那块榜写,不能藏在文档里。
 *
 * ## 说清楚的是「哪一半不打折」,不是「离线很差」
 *
 * 离线本来就一直在推进别的:修为、灵气、材料、钻研、历练场次与普通际遇。
 * 若这一句写成「离线不推进」,反而说反了 —— 玩家会以为挂机毫无意义。
 * 故落点是「**奇缘这一种要你在场**」,而不是「离线没用」。
 *
 * ## 说明写成**替玩家留着**,不是克扣
 *
 * 光说「离线不推进」会被读成限制。这一句要把理由说出来:那些选择有代价、
 * 不可逆,替玩家选等于替他做一个不能反悔的决定 —— 所以系统宁可不选。
 *
 * 与 `ui/lifeFootprint`、`ui/enemyLoreLedger` 同一层:只算,不读 store。
 */

/**
 * 奇缘的离线口径 —— 一句,接在奇缘榜下面。
 *
 * 措辞刻意落在「替你把这一步留着」而不是「离线不给」:同样是事实,
 * 前者回答「为什么挂机没动」,后者只会让玩家觉得被克扣。
 */
export function offlineChainNote(): string {
  return "奇缘只在线推进 —— 那些抉择有代价且多半不可逆,离线不替你把这一步拍了。挂机回来,这一程仍要你亲自走。";
}
