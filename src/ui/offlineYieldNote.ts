/**
 * 洞府「每时藏收」的离线口径说明
 *
 * ## 缺口:页面上的速率是**全额**,离线结算是 **9 折**
 *
 * 洞府页的「每时藏收」由 `core/engineFacilities.hourlyYieldText` 给出,读的是
 * `buildingRates(levels)` —— **全额速率**,与实时 accrual 同源。
 *
 * 而离线结算(`core/offline`)对材料/钻研/历练恒有 `OFFLINE_EFFICIENCY = 0.9` 的挂机折扣。
 * `offline.ts` 的注释自己就点出了这件事:
 *
 * ```text
 *   挂机折扣是**恒有的**(每天离线都按 9 折折算材料/钻研/历练),不是封顶才发生的事;
 *   只在超限时提一句,绝大多数短离拿到 9 折产出却以为"少了点什么",就把机制藏起来了。
 * ```
 *
 * 于是机制那边承认「藏起来了」,只在**超限**的归来卷轴上才提。可这一页就在玩家眼前
 * 摆着「每时藏收 灵草 30 株」,他乘 72 小时算出一个数,实际到手是 2160×0.9。
 * 而「离线能攒多久」「攒满是多少」正是这一页帮玩家做的决定。
 *
 * ## 不改数值,只加口径
 *
 * `hourlyYieldText` 是**实时 accrual 的真值**,离线那 9 折只在离线那一侧发生 ——
 * 改它的数值会让在线结算变成假的。故只在这一行后面加一句限定。
 *
 * ## 常数的两半都要说
 *
 * `offline.ts` 的披露原文是「修为与灵气按时长**全额**入账;材料、钻研与历练按 N 折挂机」。
 * 若简化成「离线一律 N 折」,就把「修为灵气不打折」这条**对玩家有利**的规则说反了 ——
 * 那比不说更糟。故这一句两条都要。
 *
 * ## 这一层只算,不读 store
 *
 * 与 `ui/lifeFootprint`、`ui/reincarnationDesk` 同一条纪律:收参数、给纯值。
 */
import { OFFLINE_EFFICIENCY } from "@/data/constants";

/**
 * 一句离线口径:实时全额,离线按几折,以及哪几类不受影响。
 *
 * 折数从 `OFFLINE_EFFICIENCY` 现算(`0.9 → 9`)—— 改常数时文案自己跟上,
 * 不在界面手写「9 折」。
 */
export function offlineYieldNote(efficiency: number = OFFLINE_EFFICIENCY): string {
  /*
   * `× 10` 之后再收敛小数:0.9 → 9、0.85 → 8.5。写成「8.5 折」而不是「9 折」——
   * 四舍五入会把一个更小的折扣说大,那是往玩家有利的方向撒谎。
   */
  const fold = Math.round(efficiency * 100) / 10;
  const foldText = Number.isInteger(fold) ? String(fold) : fold.toFixed(1);
  /*
   * **只补上面那个速率缺的那半句话。**
   *
   * 同一页的「离线存续」区已经写着「修为与灵气全额计入;材料、钻研与历练按 N 折挂机」——
   * 那是**上限**那一格的账。这里若把同一句再写一遍,就是同一事实在同一页说两遍,
   * 正是本仓「不做两本账」要避免的。
   *
   * 故这句只答一个问题:「每时藏收」那个速率,离线时是不是同一个数?
   * 答案:不是 —— 它记的是实时全额,离线要折。折多少、哪几类打折,去下面那一格看。
   */
  return `此数为实时全额;离线挂机按 ${foldText} 折计(口径与上限见下「离线存续」)。`;
}
