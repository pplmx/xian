/**
 * 差额一句话 —— 「灵石不足」与「尚差 320 石」的分别,是能不能安排下一步。
 *
 * ## 为什么这值得一个模块
 *
 * 本仓有两条纪律,一条已经做得很彻底,另一条还在补:
 *   **付不起置灰 + 把差多少列出来** —— 按钮那一侧几乎处处做到了;
 *   **同一件事在被拦下时说清楚** —— 点下去之后弹的那句提示,却常常只说「不足」。
 *
 * 玩家点一下得到「灵石或器灵尘不足」,与得到「尚差 器灵尘×120 · 灵石 3.4万」
 * 是两种境遇:前者要自己去换算,后者能直接决定「先去刷一趟还是先卖点东西」。
 *
 * ## 为什么不是一个通用格式化器
 *
 * 各处的资源名、单位、量纲都不同(石 / 器灵尘 / 悟道点 / 玄铁 / 道源),
 * 硬统一会把「3.4万 石」写成「3.4万」而丢单位。故这里只提供**拼法**:
 * 调用方给出「哪几样差多少」,这里负责连成一句、并在只缺一样时不写多余的分隔。
 *
 * ## 与置灰那一侧同源
 *
 * 差额由调用方从**同一份代价与同一份持有**算出(不另算一份),这里不做减法 ——
 * 它只拼句子。这样「按钮上写的」与「点下去说的」不会分叉。
 */

/** 一样东西差多少 */
export interface Shortfall {
  /** 人话名目(石头 / 器灵尘 / 悟道点 / 玄铁 / 道源) */
  name: string;
  /** 已格式化的差额(调用方用该资源自己的格式化器,不在这里猜量纲) */
  amount: string;
}

/**
 * 「尚差 X 石」/「尚差 器灵尘×120 · 灵石 3.4万」。
 *
 * 只缺一样时不写分隔符 —— 「尚差 320 石」比「尚差 320 石 · 」干净。
 * 一样都不缺时给空串:调用方据此决定这句要不要说(没差额就不该拦人)。
 */
export function shortfallText(rows: readonly Shortfall[]): string {
  const parts = rows
    .filter((row) => row.name.length > 0 && row.amount.length > 0)
    .map((row) => `${row.name} ${row.amount}`);
  if (parts.length === 0) return "";
  return `尚差 ${parts.join(" · ")}`;
}

/**
 * 与一个前缀合成整句:「灵石不足 —— 尚差 320 石」。
 *
 * 为什么保留前缀:玩家点的那一下得先知道**为什么没成**(是灵石不足,不是别的原因),
 * 再知道差多少。只报差额会让「什么没成」变得要靠上下文猜。
 */
export function blockedBy(prefix: string, rows: readonly Shortfall[]): string {
  const gap = shortfallText(rows);
  return gap ? `${prefix} —— ${gap}` : prefix;
}
