/**
 * 册次水印 —— 卷首那枚最大的字,该是汉字而不是阿拉伯数字。
 *
 * ## 问题:页面上最大的字,是唯一一处阿拉伯数字
 *
 * 每一页卷首都压着一枚水印(4.6rem ~ 8.5rem,全屏最大的字),写着「01」「02」「03」。
 * 而这一作里所有**读得出来**的序数都是汉字:卷次写「卷三」、章序写「壹贰叁」、
 * 页签写「乙」「丙」、灵兽档写「已录」。唯独压在整页最底下的那枚是阿拉伯数字。
 *
 * 它不是小数目标:这枚字占了几乎整块卷首的视觉重量,却与周围的丹青语言不是同一套。
 * 换成汉字之后,「第几册」这件事在两层上(卷次小字 + 水印大字)说的是同一种话。
 *
 * ## 为什么要留 `data-folio-ordinal` 的原值
 *
 * 那枚字是 `aria-hidden` 的纯装饰,读屏不念它 —— 但判据要能核「水印说的是第几册」。
 * 故数字仍留在 data 属性上(与册目位置同源),视觉上换成汉字:
 * 一个是机器核对的口径,一个是玩家看到的写法,两者都从 `navigationPositionOf` 来。
 *
 * ## 十以上怎么办
 *
 * 全作只有十七页(卷一至卷五),册次不会超过二十。但 `cnNumber` 的行为要钉住:
 * 10 读「十」不是「一十」、11 读「十一」,与 format.ts 已有的规则同一份实现 ——
 * 这里不另写一个数字转汉字的函数。
 */
import { cnNumber } from "@/utils/format";

/** 册次水印的写法:汉字;0 或坏值退成「零」而不是空 */
export function folioOrdinalMark(entryIndex: number): string {
  if (!Number.isFinite(entryIndex)) return "零";
  const n = Math.floor(entryIndex) + 1;
  if (n < 1) return "零";
  return cnNumber(n);
}
