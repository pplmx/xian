/**
 * 玉振的声音 —— 神品落地与灵品落地,不该是同一响。
 *
 * ## 问题:声音是最后一个没分层的感官
 *
 * 品阶在三个层面已经分层了:
 *   颜色与边框(第 18 轮)    灵/玄/地 一档、天仙 一档、神 一档
 *   全屏那道光(第 21 轮)    1.1s / 1.35s / 1.6s
 *   提示条上那枚印(第 5 轮) 色与单字都取自品质表
 *
 * 而**声音**至今只有一种:`rare` 一响,管钟 D5 加一声高音 D7 —— 无论这一件是
 * 灵品还是神品。视觉层已经说「这一件更重」,声音层还在说「都一样」,两句话矛盾。
 *
 * ## 补什么
 *
 * 三层,用**音高与声部数**分,不用音量分:
 *
 *   rare(灵/玄/地)  —— 原有那一响,一个音都不改
 *   rareHigh(天/仙)  —— 管钟升到 F5,高音加一声 A7
 *   rareTop(神)      —— 管钟升到 A5,并补一个低八度 A3 作根基
 *
 * ## 为什么用音高而不是音量
 *
 * 音量在手机扬声器上几乎听不出差别(尤其开了系统限幅),而**音高与和声的厚度**
 * 会变。这三层的相对关系是「同一口钟,敲在更高的地方」—— 同一族声音里的层级,
 * 而不是三种不同的铃。
 *
 * ## 为什么不复用 `breakthrough`
 *
 * 那一响是整条刮奏冲顶 + 管钟定音,属于**大境界突破**这件事本身。
 * 神品法宝落地若也用它,玩家会分不清刚才过的是哪一件 —— 声音的语义会被稀释。
 * 稀有品阶始终留在「管钟」这一族里。
 */

/** 稀有提示的三层音 */
export type RareSfxTier = "rare" | "rareHigh" | "rareTop";

/**
 * 品阶印 → 该响哪一声。
 *
 * 与视觉层同一条界(见 ui/qualityTier 的稀有段、ui/flashTier 的 rank ≥ 6):
 *   rank < 6 —— rare,即原来那一响
 *   rank 6-7 —— rareHigh
 *   rank 8   —— rareTop
 *
 * 没有印时也走 rare:转世/突破/里程碑那些提示不该被这一改动惊动。
 */
export function rareSfxOf(rank: number | undefined): RareSfxTier {
  const r = typeof rank === "number" && Number.isFinite(rank) ? rank : 0;
  if (r >= 8) return "rareTop";
  if (r >= 6) return "rareHigh";
  return "rare";
}
