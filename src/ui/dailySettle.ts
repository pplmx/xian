/**
 * 日课结契 —— 今日功课全清时,那枚印上写什么。
 *
 * ## 现状
 *
 * 首页「今日日课」那张卡做得细:进度环、逐笔进度、奖励同格摊开、完成态划线。
 * 但**全清那一刻**只有三处静态变化(标题、正文、一个 `is-complete` 类),
 * 屏幕上没有发生任何**事件** —— 只有字换了。
 *
 * ## 为什么这一处值得一笔收束
 *
 * 日课是玩家每天都会经历一次的那条路径,也是放置游戏里最容易被忽略的节拍:
 * 它重复、可预期、做完就过去了。而「重复的事被郑重对待一次」正是仪式感的来源 ——
 * 不靠特效堆,靠**世界承认你做完了**。
 *
 * 中文修仙语汇里对应的词是「契」:日课与天时有约,做完便是**结契**。
 * 比「完成」「达成」这类系统词更贴这本书的口吻(与道记、器铭同一路)。
 *
 * ## 不编号
 *
 * 本作没有累计天数的账(日课按天重置,不编号)。若落款写「第 N 日」,
 * 那个 N 要么是编的,要么得从别处借一个与本意无关的数。故只承认"今天这一期结了"。
 *
 * ## 只做措辞
 *
 * 判定复用首页既有的 `dailyAllDone`(长度 > 0 且每笔 done)—— 它已经正确,
 * 再抽一份只是搬家,还会多一处要同步维护的判定。
 */

/** 那枚印上写什么 */
export function dailySettleSeal(): string {
  return "日课已结";
}
