/** 把一组笔路包成组件:尺寸与线宽都由 GameIcon 传进来 */
function inkIcon(paths: string[]): Component {
  return defineComponent({
    name: 'InkIcon',
    props: {
      size: { type: Number, default: 16 },
      strokeWidth: { type: [Number, String] as PropType<number | string>, default: 1.8 }
    },
    setup(props) {
      /*
       * 水墨笔路比几何直线细:同样线宽下,长弧线的视觉重量比短直线轻,按 1.8 画出来
       * 会显得发飘(对着 20px 的底栏比过)。故这里抬到 2 起步 ——
       * 调用方要更粗仍可传更大的值。
       */
      const strokeWidth = Math.max(2, Number(props.strokeWidth) || 1.8)
      return () =>
        h(
          'svg',
          {
            width: props.size,
            height: props.size,
            viewBox: '0 0 24 24',
            fill: 'none',
            stroke: 'currentColor',
            'stroke-width': strokeWidth,
            'stroke-linecap': 'round',
            'stroke-linejoin': 'round',
            'aria-hidden': 'true'
          },
          paths.map(d => h('path', { d }))
        )
    }
  })
}

export const INK_ICONS: Record<string, Component> = Object.fromEntries(
  Object.entries(INK).map(([name, paths]) => [name, inkIcon(paths)])
)

/**
 * 按名取图标。认不出的名字落到星芒,而不是报错 —— 图标名写错在界面上只是「少了一枚」,
 * 若在这里抛异常,一条写错的名字会让整页白屏;`inkIcons.spec.ts` 那条「写死的名字必须
 * 登记过」才是拦它的地方。
 */
export function iconOf(name: string): Component {
  return INK_ICONS[name] ?? INK_ICONS.sparkles!
}
