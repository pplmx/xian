/**
 * 道果「再凝一枚」那一行 —— `+7.47%` 到底是谁的 7.47%?
 *
 * ## 复现:两个不同量纲的百分比上下并排
 *
 * 兵解往生的「贰 随魂所积」一节是这样排的:
 *
 * ```text
 * 当前有效收益    9.4 枚
 * 修行加成       +28.1%
 * 再凝一枚       有效 10.1 枚 · +7.47%
 * 每枚名义:修行 +3%,道躯 +2%。
 * ```
 *
 * 倒数第二行那个 `+7.47%` 是**有效道果的增长率**
 * (`core/resourceGuidance` 的 `(nextEff - eff) / eff`),
 * 与上面那个 +28.1% 是**两个量纲**:
 *
 *   +28.1%  —— 修行加成(由有效道果折算出来的加成幅度)
 *   +7.47%  —— 再凝一枚时,有效道果本身的增幅
 *
 * 而它们上下并排、都带 `+`、都以 `%` 结尾。读者几乎必然读成
 * 「再攒一枚,修行加成再加 7.47%」—— 实际上再加一枚后修行加成会从
 * +28.1% 涨到大约 +30.2%(28.1 × 1.0747),而不是 +35.57%。
 *
 * ## 为什么这一处值得改
 *
 * 这是**玩家决定要不要继续攒道果**的那一格。道果是跨世唯一的永久积累,
 * 而「再凝一枚能多多少」正是这个决定的核心读数。读错了量纲,玩家会高估
 * 或低估这一枚的价值 —— 而它每一枚都要一世的修行去换。
 *
 * ## 判据守什么
 *
 * 一条:`+N%` 前面必须写清它是什么的增幅。
 *
 * 不要求改数值(那是 `resourceGuidance` 的事,而且它的注释里写了为什么
 * 用两位小数、为什么不能取整),只要求**把量纲说出来**。
 */
import { describe, expect, it } from "vite-plus/test";
import { readSource } from "@/test/readSource";

const DLG = "src/components/character/RebirthDialog.vue";

describe("道果 · 再凝一枚那一行要说清是谁的增幅", () => {
  it("`+N%` 前面有量纲主语,不是裸的百分比", () => {
    const src = readSource(DLG);
    const row = src.match(/再凝一枚[\s\S]{0,300}/)?.[0] ?? "";
    expect(row, "定位不到「再凝一枚」那一行 —— 判据会空转").not.toBe("");
    /*
     * 裸写法:`· +{{ fruitInfo.deltaPct }}%`
     * 合格写法要在这个百分比前交代它量的是「道果收益」而不是「修行加成」。
     */
    expect(
      row,
      "再凝一枚的百分比要写明量的是道果收益的增幅 —— 它上面一行正是修行加成,两个不同量纲并排会被读成同一个",
    ).toMatch(/道果|收益/);
  });

  it("与「修行加成」是两个量纲 —— 不许混成一行", () => {
    const src = readSource(DLG);
    // 「修行加成」仍是它自己那一行(不许被合并进「再凝一枚」)
    expect(src, "修行加成那一行仍在").toContain("修行加成");
  });

  it("反空转:数值本身仍读 fruitInfo,不手抄", () => {
    const src = readSource(DLG);
    expect(src, "增幅仍要读 fruitInfo.deltaPct").toContain("fruitInfo.deltaPct");
  });
});
