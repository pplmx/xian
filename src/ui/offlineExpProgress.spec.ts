/**
 * 离线归来 —— 修为那一行该说「这够你推几层」,不只是「+42 亿」。
 *
 * ## 现状
 *
 * 归来卷轴的「入账」组第一行是:
 *
 * ```text
 * 修为   +42亿
 * ```
 *
 * 数字对,也确实是这次挂机挣的。但它回答不了玩家醒来时真正想问的那件事:
 * **「那我现在的境界推到哪儿了?」**
 *
 * 而修行页上「本境修为」那一格给的是「2.784亿 / 29.69兆 · 还剩 100%」——
 * 两屏各自说一半:卷轴说「你挣了多少」,修行页说「你还差多少」,
 * 中间那句「这次离线推了本境多少」谁也不说。
 *
 * ## 为什么这一处值得补
 *
 * 放置游戏的归来结算,玩家真正在意的排序是:
 *
 *   一 我变强了多少(修为涨了多少)—— 已有
 *   二 **这相当于走到了哪一步** —— 缺
 *   三 带回了什么东西 —— 已有
 *
 * 第二条缺着,「+42亿」就只是个抽象的大数:它可能是一个时辰的量,
 * 也可能是一天一夜的量,玩家没有参照。
 *
 * ## 判据守什么
 *
 * 两条:
 *   一 修为那一行的值里带上「本境推进」的说法(读 expReq 现算,不另存);
 *   二 跨层时要说清跨了几层 —— 只写百分比的话,「0% → 4%」与「0% → 96%」
 *      在玩家眼里是同一个「涨了一点」。
 *
 * 不要求改结算逻辑:修为本来就按真实离线时长全额入账(见 core/offline 那段注释),
 * 这一条只补**展示**,不动任何数值。
 */
import { describe, expect, it } from "vite-plus/test";
import { readSource } from "@/test/readSource";

const DLG = "src/components/offline/OfflineRewardDialog.vue";

describe("离线归来 · 修为要说清推到了哪儿", () => {
  it("修为那一行带本境推进", () => {
    const src = readSource(DLG);
    /*
     * 判据查的是「修为那一行最终的 value 表达式里有没有推进」——
     * 推进文案由 push 变量拼进去,故定位到 list.push 那一行即可,
     * 不要求字面量直接写在里面。
     */
    const expRow = src.split("\n").find((l) => l.includes('label: "修为"')) ?? "";
    expect(expRow, "定位不到修为那一行 —— 判据会空转").not.toBe("");
    expect(expRow, "修为行的 value 里要拼上推进").toContain("push");
    expect(src, "推进文案本身要报「本境推 N 层」或「本境 X%」").toMatch(
      /本境推|本境 \$\{formatPercent/,
    );
    /*
     * 门槛:高境界下一次通宵可能只占本境需求万分之几,写成「本境 0%」等于没说。
     * 故不足 1% 时那一截不占字 —— 判据要钉住这个门槛,否则有人把 push 改成
     * 「总是拼上」,归来卷轴又会多出一句没有信息量的「本境 0%」。
     */
    expect(src, "不足 1% 时不该硬报百分比").toMatch(/layers >= 0\.01/);
  });

  it("推进量现算,不另存一份", () => {
    /*
     * 分母必须读 player.expReq(与修行页的进度条同一份),不许在弹窗里
     * 另存一个「本境所需修为」。两本账迟早对不上。
     */
    const src = readSource(DLG);
    expect(src, "推进量要读 player.expReq 现算").toContain("expReq");
  });

  it("反空转:修为的绝对值仍要报 —— 推进是补充,不是替代", () => {
    const src = readSource(DLG);
    expect(src, "「+N 亿」那个绝对值仍在").toContain("formatGN(s.exp)");
  });
});
